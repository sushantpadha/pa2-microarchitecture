#!/usr/bin/env python3
"""Write the Task 3 tables and figures from data/task3 and data/task3_modes.

Usage: python3 report/task3.py
    writes report/tables/t3_*.tex and report/figures/t3_*.png

data/task3        final run of the submitted policy: SPP alone, Dynamic I-RRIP
                  alone, and SPP + Dynamic I-RRIP with and without prefetch awareness
data/task3_modes  the prefetch knobs (PF_HIT, PF_INS, PF_TIE) of the working copy of
                  the policy, with the mode pinned (DYN_THRESH 0 = always I-RRIP,
                  1 = always RRIP)
Means over traces: geometric for speedup and ratios, arithmetic otherwise
(same as tools/exp.py).
"""
import re
import sys

import numpy as np
import pandas as pd

import tables
from tables import mean, tabular
from plots import bars, OUT as FIG   # importing plots sets the figure style

DATA, TAB = tables.DATA, tables.OUT
MAIN, MODES = "task3", "task3_modes"

# config name in data/task3/stats.csv -> label
CONFIGS = [("spp", "SPP"), ("dyn", "Dyn. I-RRIP"), ("spp_dyn_unaware", "SPP + Dyn. (unaware)"),
           ("spp_dyn", "SPP + Dyn. (aware)")]
COLS = {
    "ipc": ("IPC", "{:.4f}"),
    "speedup": ("Speedup", "{:.4f}"),
    "l1d_accuracy_issued": ("Accuracy (\\%)", "{:.1f}"),
    "l1d_coverage": ("Coverage (\\%)", "{:.1f}"),
    "l1d_load_mpki": ("L1D", "{:.2f}"),
    "l2c_load_mpki": ("L2C", "{:.2f}"),
    "l2c_instr_load_mpki": ("L2C instr.", "{:.2f}"),
    "l2c_data_load_mpki": ("L2C data", "{:.2f}"),
}
MPKI = ["l1d_load_mpki", "l2c_load_mpki", "l2c_instr_load_mpki", "l2c_data_load_mpki"]


def write(name, text):
    (TAB / name).write_text(f"% Generated by report/task3.py from data/. Do not edit by hand.\n{text}")
    print(f"[task3] {name}")


def load(task):
    return pd.read_csv(DATA / task / "stats.csv")


def fmt(m, v):
    return "--" if pd.isna(v) else COLS[m][1].format(v)


def per_trace(df, configs, metrics, name):
    """One block of rows per trace, then a mean block."""
    traces = sorted(df.trace.unique())
    rows, rules = [], []
    for block in traces + ["Mean"]:
        rules.append(len(rows))
        for j, (c, label) in enumerate(configs):
            d = df[df.config == c].set_index("trace")
            assert len(d) == len(traces), f"{c}: {len(d)} traces"
            vals = [d.loc[block, m] if block != "Mean" else mean(d[m], m == "speedup") for m in metrics]
            no_pf = c == "dyn"   # no prefetcher: accuracy and coverage do not apply
            rows.append([block if j == 0 else "", label]
                        + ["--" if no_pf and m in ("l1d_accuracy_issued", "l1d_coverage") else fmt(m, v)
                           for m, v in zip(metrics, vals)])
    header = ["Trace", "Config"] + [COLS[m][0] for m in metrics]
    write(name, tabular(header, rows, "ll" + "r" * len(metrics), rules[1:]))


def ratios(df, configs, ref, ref_label, name):
    """Mean MPKI of each config, then each MPKI as a ratio to `ref` (geomean of per-trace ratios)."""
    r = df[df.config == ref].set_index("trace")
    rows = []
    for c, label in configs:
        d = df[df.config == c].set_index("trace")
        rows.append([label] + [fmt(m, mean(d[m], False)) for m in MPKI]
                    + ["{:.3f}".format(mean(d[m] / r.loc[d.index, m], True)) for m in MPKI])
    short = ["L1D", "L2C", "Instr.", "Data"]
    top = [f"& \\multicolumn{{4}}{{c}}{{Load MPKI}} & \\multicolumn{{4}}{{c}}{{Ratio to {ref_label}}} \\\\",
           "\\cmidrule(lr){2-5} \\cmidrule(l){6-9}"]
    write(name, tabular(["Config"] + short + short, rows, "l" + "r" * 8, top=top))


def dead_counts(log, leaders):
    """{kind: (used, dead)} from the DYN_IRRIP_DEAD line (all sets) or the
    DYN_IRRIP_DEAD_LEADERS line (leader sets, plain RRIP) of a log."""
    tag = "DYN_IRRIP_DEAD_LEADERS" if leaders else "DYN_IRRIP_DEAD"
    line = re.search(rf"^{tag} (.*)$", log.read_text(errors="ignore"), re.M).group(1).split()
    return {line[i]: (int(line[i + 1]), int(line[i + 2])) for i in range(0, len(line), 3)}


TRACES = ["Trace1", "Trace2", "Trace3"]
RRIP, IRRIP = "rrip.PF_HIT=0.PF_INS=0.PF_TIE=0", "irrip.PF_HIT=0.PF_TIE=0"   # pinned, rule off

# (data folder, config, leader sets only?, label) for the deadness table
DEAD_CONFIGS = [
    (MODES, RRIP, False, "RRIP"),
    (MODES, "rrip.PF_HIT=1.PF_INS=1.PF_TIE=0", False, "RRIP + rule"),
    (MODES, IRRIP, False, "I-RRIP"),
    (MODES, IRRIP, True, "I-RRIP run, leader sets"),
    (MAIN, "spp_dyn", False, "Dyn. I-RRIP + rule"),
]
DEAD_KINDS = [("pf", "Prefetch fill"), ("data", "Demand data"), ("instr", "Instruction")]


def deadness(name):
    """Per config, fill kind and trace: % of evicted L2C lines that got a demand hit
    before eviction. Every config runs with SPP; RRIP and I-RRIP rows pin the follower
    sets to one mode. Leader sets always run plain RRIP."""
    traces = TRACES
    rows = []
    for task, config, leaders, label in DEAD_CONFIGS:
        cells = []
        for k, _ in DEAD_KINDS:
            for t in traces:
                u, d = dead_counts(DATA / task / config / f"{t}.log", leaders)[k]
                cells.append("{:.1f}".format(100 * u / (u + d)))
        rows.append([label] + cells)
    n = len(traces)
    top = ["& " + " & ".join(f"\\multicolumn{{{n}}}{{c}}{{{l}}}" for _, l in DEAD_KINDS) + " \\\\",
           " ".join(f"\\cmidrule(lr){{{2 + n * i}-{1 + n * (i + 1)}}}" for i in range(len(DEAD_KINDS)))]
    header = ["L2C policy"] + [t.replace("Trace", "T") for t in traces] * len(DEAD_KINDS)
    write(name, tabular(header, rows, "l" + "r" * (n * len(DEAD_KINDS)), top=top))


def evictions(name):
    """L2C evictions (thousands, all sets) by what filled the victim, RRIP vs I-RRIP
    pinned, SPP on, prefetch rule off."""
    rows = []
    for k, label in [("data", "Demand data"), ("instr", "Instruction"), (None, "All")]:
        for config, mode in [(RRIP, "RRIP"), (IRRIP, "I-RRIP")]:
            cells = []
            for t in TRACES:
                c = dead_counts(DATA / MODES / config / f"{t}.log", False)
                n = sum(map(sum, c.values())) if k is None else sum(c[k])
                cells.append("{:.0f}".format(n / 1000))
            rows.append([label if mode == "RRIP" else "", mode] + cells)
    write(name, tabular(["Victim filled by", "Policy", "T1", "T2", "T3"], rows, "llrrr", [2, 4]))


def modes(name):
    """Pinned mode: speedup and L2C MPKI (means, and ratio to the unaware row) per knob combination."""
    df = load(MODES)
    rows, rules = [], []
    for mode, label, combos in [
            ("irrip", "I-RRIP", [("PF_HIT=0.PF_TIE=0", "0", "--", "0"), ("PF_HIT=1.PF_TIE=0", "1", "--", "0"),
                                 ("PF_HIT=0.PF_TIE=1", "0", "--", "1"), ("PF_HIT=1.PF_TIE=1", "1", "--", "1")]),
            ("rrip", "RRIP", [(f"PF_HIT={h}.PF_INS={i}.PF_TIE={t}", h, i, t)
                              for t in "01" for i in "01" for h in "01"])]:
        rules.append(len(rows))
        ref = df[df.config == f"{mode}.{combos[0][0]}"].set_index("trace")
        for j, (c, h, i, t) in enumerate(combos):
            d = df[df.config == f"{mode}.{c}"].set_index("trace")
            assert len(d) == 3, c
            rows.append([label if j == 0 else "", h, i, t, "{:.4f}".format(mean(d.speedup, True))]
                        + [fmt(m, mean(d[m], False)) for m in ("l2c_load_mpki", "l2c_instr_load_mpki")]
                        + ["{:.3f}".format(mean(d[m] / ref.loc[d.index, m], True)) for m in ("l2c_load_mpki", "l2c_instr_load_mpki")])
    header = ["Mode", "Hit", "Insert", "Evict", "Speedup",
              "L2C", "Instr.", "L2C", "Instr."]
    top = ["& & & & & \\multicolumn{2}{c}{Load MPKI} & \\multicolumn{2}{c}{Ratio to first row} \\\\",
           "\\cmidrule(lr){6-7} \\cmidrule(l){8-9}"]
    write(name, tabular(header, rows, "llllrrrrr", rules[1:], top=top))


def figures():
    c = [("base", "Baseline")] + CONFIGS
    bars(MAIN, "speedup", CONFIGS, "Speedup", "Speedup over baseline", "t3_speedup.png", ref=1.0, first_color=1)
    bars(MAIN, "ipc", c, "IPC", "IPC", "t3_ipc.png")
    pf = [x for x in CONFIGS if x[0] != "dyn"]
    bars(MAIN, "l1d_accuracy_issued", pf, "Accuracy (%)", "L1D prefetch accuracy", "t3_accuracy.png", first_color=1)
    bars(MAIN, "l1d_coverage", pf, "Coverage (%)", "L1D prefetch coverage", "t3_coverage.png", first_color=1)
    for m, title in [("l1d_load_mpki", "L1D"), ("l2c_load_mpki", "L2C"),
                     ("l2c_instr_load_mpki", "L2C instruction"), ("l2c_data_load_mpki", "L2C data")]:
        bars(MAIN, m, c, "MPKI", f"{title} load MPKI", f"t3_{m.replace('_load_mpki', '')}.png")


def main():
    df = load(MAIN)
    per_trace(df, CONFIGS, ["ipc", "speedup", "l1d_accuracy_issued", "l1d_coverage"], "t3_perf.tex")
    per_trace(df, CONFIGS, MPKI, "t3_mpki.tex")
    ratios(df, [("base", "Baseline")] + CONFIGS, "base", "baseline", "t3_ratios.tex")
    deadness("t3_dead.tex")
    evictions("t3_evict.tex")
    modes("t3_modes.tex")
    figures()


if __name__ == "__main__":
    if len(sys.argv) > 1:   # test against another directory: report/task3.py <dir with task3/ and task3_modes/>
        DATA = tables.DATA = __import__("pathlib").Path(sys.argv[1])
        import plots; plots.DATA = DATA
    main()
