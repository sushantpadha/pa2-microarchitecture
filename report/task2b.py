#!/usr/bin/env python3
"""Write the Task 2B tables and figures from data/task2b_sweep, task2b_hyst and task2b_grid.

Usage: python3 report/task2b.py
    writes report/tables/t2b_*.tex and report/figures/t2b_*.png (sweep figures, and
    per-trace bar charts of the chosen config like report/plots.py makes for 2A)

Sweeps (each varies one knob; the fixed values are per sweep, see main()):
- threshold T (8 leaders, epoch 512), leader count (T = 0.15, epoch 1024), epoch
  (32 leaders, T = 0.15): from task2b_sweep (placement 0, no hysteresis)
- hysteresis: from task2b_hyst (32 leaders, epoch 1024, T = 0.15, placement 0)
- placement: from task2b_grid, the only run with placements 1 and 2 (its epoch is
  32 leader accesses per leader set, so 32 leaders = epoch 1024, as in FIX_E)
The reference config for every MPKI ratio is static I-RRIP ("irrip"), which uses
the same rules as dyn_irrip's I-RRIP mode. Means over traces: geometric for
speedup and ratios, arithmetic otherwise (same as tools/exp.py).
"""
import shutil

import numpy as np
import pandas as pd

import tables
from tables import COLS, MPKI, mean, tabular
import plots
from plots import COLORS, GRID, INK, OUT as FIG, plt   # importing plots sets the figure style

DATA, TAB = tables.DATA, tables.OUT

# Values shown in the report, and the fixed values of the knobs not being swept.
THRESHS = ["0", "0.15", "0.25", "0.4", "0.5"]
LEADERS = [8, 16, 32, 64]
EPOCHS = [512, 1024, 2048]
PLACES = {0: "complement select", 1: "low bits = 0", 2: "first sets"}
HYSTS = ["0", "0.05", "0.1"]
FIX_T, FIX_N, FIX_E, FIX_P = "0.15", 32, 1024, 0   # epoch, hysteresis and placement sweeps
# The chosen configuration = dyn_irrip's code defaults: placement 0, 8 leaders,
# epoch 1024, T = 0.15, h = 0.05. (Checked: a no-env build prints these values and
# matches the same config set through env exactly. Same results as h = 0 in task2b_sweep.)
BEST = ("task2b_hyst", "n8.DYN_EPOCH=1024.DYN_HYST=0.05")


def grid(n, p, t):
    return f"n{n}.DYN_PLACE={p}.DYN_THRESH={t}"


def sweep(n, e, t):
    return f"n{n}.DYN_EPOCH={e}.DYN_THRESH={t}"


def write(name, text):
    (TAB / name).write_text(f"% Generated by report/task2b.py from data/. Do not edit by hand.\n{text}")
    print(f"[task2b] {name}")


def summary(task, configs):
    """configs: [(config, label)] -> DataFrame, one row per config: the trace means
    of every metric plus each MPKI as a ratio to irrip."""
    df = pd.read_csv(DATA / task / "stats.csv")
    ref = df[df.config == "irrip"].set_index("trace")
    rows = []
    for c, label in configs:
        d = df[df.config == c].set_index("trace")
        assert len(d) == len(ref), f"{task}: {c} has {len(d)} traces"
        row = {"label": label, **{m: mean(d[m], m == "speedup") for m in COLS}}
        row.update({m + "_r": mean(d[m] / ref.loc[d.index, m], True) for m in MPKI})
        rows.append(row)
    return pd.DataFrame(rows)


def sweep_table(s, name, knob):
    """Rows: the two static references, then one row per swept value."""
    rows = [[r.label] + [COLS[m][1].format(r[m]) for m in COLS] + ["{:.3f}".format(r[m + "_r"]) for m in MPKI]
            for _, r in s.iterrows()]
    short = ["L2C", "Instr.", "Data"]
    header = [knob, "IPC", "Speedup"] + short + short
    top = ["& & & \\multicolumn{3}{c}{Load MPKI} & \\multicolumn{3}{c}{MPKI ratio to I-RRIP} \\\\",
           "\\cmidrule(lr){4-6} \\cmidrule(l){7-9}"]
    write(name, tabular(header, rows, "l" + "r" * 8, rules=(2,), top=top))


def sweep_figure(s, name, xlabel):
    """Left: speedup over LRU per value, with the static policies as lines.
    Right: each MPKI as a ratio to I-RRIP."""
    ref, x = s.iloc[:2], s.iloc[2:]
    pos = np.arange(len(x))
    fig, (a, b) = plt.subplots(1, 2, figsize=(7.2, 2.6))
    a.plot(pos, x.speedup, "o-", color=COLORS[0], label="Dynamic I-RRIP", zorder=3)
    for (r, style) in zip(ref.itertuples(), ["--", ":"]):
        a.axhline(r.speedup, color=INK, linestyle=style, linewidth=1, label=r.label)
    a.set_ylabel("Speedup over LRU (geomean)")
    for i, (m, label) in enumerate(zip(MPKI, ["L2C", "Instr.", "Data"])):
        b.plot(pos, x[m + "_r"], "o-", color=COLORS[i + 1], label=label, zorder=3)
    b.axhline(1, color=INK, linestyle="--", linewidth=1)
    b.set_ylabel("Load MPKI / I-RRIP")
    for ax in (a, b):
        ax.set_xticks(pos, x.label)
        ax.set_xlabel(xlabel)
        ax.yaxis.grid(True, color=GRID, linewidth=0.6, zorder=0)
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / name)
    plt.close(fig)
    print(f"[task2b] {name}")


STATIC = [("rrip", "SRRIP"), ("irrip", "I-RRIP")]


def main():
    g, sw, hy = "task2b_grid", "task2b_sweep", "task2b_hyst"

    s = summary(sw, STATIC + [(sweep(8, 512, t), t) for t in THRESHS])
    sweep_table(s, "t2b_thresh.tex", "$T$")
    sweep_figure(s, "t2b_thresh.png", "Threshold $T$")

    s = summary(sw, STATIC + [(sweep(n, 1024, "0.15"), str(n)) for n in LEADERS])
    sweep_table(s, "t2b_leaders.tex", "Leaders")
    sweep_figure(s, "t2b_leaders.png", "Leader sets")

    s = summary(sw, STATIC + [(sweep(FIX_N, e, FIX_T), str(e)) for e in EPOCHS])
    sweep_table(s, "t2b_epoch.tex", "Epoch")
    sweep_figure(s, "t2b_epoch.png", "Epoch (leader accesses)")

    s = summary(hy, STATIC + [(f"n{FIX_N}.DYN_EPOCH={FIX_E}.DYN_HYST={h}", h) for h in HYSTS])
    sweep_table(s, "t2b_hyst.tex", "$h$")
    sweep_figure(s, "t2b_hyst.png", "Hysteresis $h$")

    # placement: speedup over LRU, one column per placement, one row per T
    rows = []
    for t in THRESHS:
        sp = [summary(g, [(grid(FIX_N, p, t), "")]).speedup[0] for p in PLACES]
        rows.append([t] + ["{:.4f}".format(v) for v in sp])
    write("t2b_place.tex", tabular(["$T$"] + list(PLACES.values()), rows, "lrrr"))

    # the chosen configuration, per trace, against the baselines
    tables.write = write   # per_trace writes through tables.write; keep our header
    tables.per_trace(BEST[0], [("base", "LRU (baseline)"), ("rrip", "SRRIP"), ("irrip", "I-RRIP"),
                               (BEST[1], "Dynamic I-RRIP")], "t2b_results.tex")
    # hysteresis figure, made by tools/task2b_analysis.py from data/task2b_hyst
    shutil.copy(DATA / "task2b_hyst" / "analysis" / "rrip_decisions_summary_e512.png", FIG / "t2b_hyst_decisions.png")
    print("[task2b] t2b_hyst_decisions.png (copied)")

    # and the PS-style per-trace bar charts: t2b_{ipc,speedup,mpki,mpki_instr,mpki_data}.png
    plots.l2_figures(BEST[0], [("rrip", "SRRIP"), ("irrip", "I-RRIP"), (BEST[1], "Dynamic I-RRIP")], "t2b")


if __name__ == "__main__":
    main()
