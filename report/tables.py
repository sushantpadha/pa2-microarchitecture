#!/usr/bin/env python3
"""Write the report's LaTeX tables from the published results in data/.

Usage: python3 report/tables.py      (writes report/tables/*.tex)

Each table is a booktabs tabular, \\input by a section file, so no number in a
table is typed by hand. Means over traces: geometric for speedup and for
ratios, arithmetic otherwise (same as tools/exp.py).
"""
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA, OUT = ROOT / "data", ROOT / "report" / "tables"

# column name in stats.csv -> (header, format)
COLS = {
    "ipc": ("IPC", "{:.4f}"),
    "speedup": ("Speedup", "{:.4f}"),
    "l2c_load_mpki": ("L2C", "{:.2f}"),
    "l2c_instr_load_mpki": ("L2C instr.", "{:.2f}"),
    "l2c_data_load_mpki": ("L2C data", "{:.2f}"),
}
MPKI = ["l2c_load_mpki", "l2c_instr_load_mpki", "l2c_data_load_mpki"]


def load(task, configs):
    df = pd.read_csv(DATA / task / "stats.csv")
    missing = [c for c in configs if c not in set(df.config)]
    assert not missing, f"{task}: no rows for {missing}"
    return df


def mean(values, geo):
    values = values.dropna()
    return float(np.exp(np.log(values).mean())) if geo else float(values.mean())


def tabular(header, rows, align, rules=(), top=()):
    """rows: lists of cell strings; rules: row indices that get a \\midrule before them;
    top: header lines (raw LaTeX) above `header`."""
    out = [f"\\begin{{tabular}}{{@{{}}{align}@{{}}}}", "\\toprule", *top, " & ".join(header) + " \\\\", "\\midrule"]
    for i, r in enumerate(rows):
        if i in rules:
            out.append("\\midrule")
        out.append(" & ".join(r) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(out)


def write(name, text):
    (OUT / name).write_text(f"% Generated by report/tables.py from data/. Do not edit by hand.\n{text}")
    print(f"[tables] {name}")


def per_trace(task, configs, name, metrics=("ipc", "speedup", *MPKI)):
    """One block of rows per trace, then a mean block. configs: [(config, label)]."""
    df = load(task, [c for c, _ in configs])
    traces = sorted(df.trace.unique())
    rows, rules = [], []
    for block in traces + ["Mean"]:
        rules.append(len(rows))
        for j, (c, label) in enumerate(configs):
            d = df[df.config == c].set_index("trace")
            vals = [d.loc[block, m] if block != "Mean" else mean(d[m], m == "speedup") for m in metrics]
            cells = [COLS[m][1].format(v) for m, v in zip(metrics, vals)]
            rows.append([block if j == 0 else "", label] + cells)
    header = ["Trace", "Policy"] + [COLS[m][0] for m in metrics]
    write(name, tabular(header, rows, "ll" + "r" * len(metrics), rules[1:]))


def means(task, configs, name, ref, ref_label, metrics=("speedup", *MPKI)):
    """One row per config: the mean of each metric, then each MPKI as a ratio to `ref`
    (geometric mean over traces of the per-trace ratio)."""
    df = load(task, [c for c, _ in configs] + [ref])
    r = df[df.config == ref].set_index("trace")
    rows = []
    for c, label in configs:
        d = df[df.config == c].set_index("trace")
        cells = [COLS[m][1].format(mean(d[m], m == "speedup")) for m in metrics]
        cells += ["{:.3f}".format(mean(d[m] / r.loc[d.index, m], True)) for m in MPKI]
        rows.append([label] + cells)
    short = ["L2C", "Instr.", "Data"]
    header = ["Policy", "Speedup"] + short + short
    top = [f"& & \\multicolumn{{3}}{{c}}{{Load MPKI}} & \\multicolumn{{3}}{{c}}{{MPKI ratio to {ref_label}}} \\\\",
           "\\cmidrule(lr){3-5} \\cmidrule(l){6-8}"]
    write(name, tabular(header, rows, "lrrrrrrr", top=top))


def roi(log):
    """ROI section of a ChampSim log (statistics after warmup)."""
    return log.read_text(errors="ignore").split("Region of Interest Statistics")[1]


def llc(task, configs, name):
    """L2C load misses and LLC load hits/misses (thousands) per trace, from the raw logs:
    shows whether the L2C misses a policy removes were LLC hits or DRAM accesses."""
    rows, rules = [], []
    traces = sorted(p.stem for p in (DATA / task / configs[0][0]).glob("Trace*.log"))
    for t in traces:
        rules.append(len(rows))
        for j, (c, label) in enumerate(configs):
            s = roi(DATA / task / c / f"{t}.log")
            l2 = re.search(r"^L2C LOAD\s+ACCESS:.*MISS:\s+(\d+)", s, re.M).group(1)
            hit, miss = re.search(r"^LLC LOAD\s+ACCESS:.*HIT:\s+(\d+)\s+MISS:\s+(\d+)", s, re.M).groups()
            rows.append([t if j == 0 else "", label] + ["{:.1f}".format(int(v) / 1000) for v in (l2, hit, miss)])
    header = ["Trace", "Policy", "L2C load misses", "LLC load hits", "LLC load misses"]
    write(name, tabular(header, rows, "llrrr", rules[1:]))


def task2a():
    t = "task2a"
    main_cfgs = [("base", "LRU (baseline)"), ("rrip", "SRRIP"), ("irrip_default", "I-RRIP")]
    per_trace(t, main_cfgs, "t2a_results.tex")
    means(t, main_cfgs, "t2a_ratios.tex", ref="base", ref_label="LRU")
    levels = [("rrip", "SRRIP")] + [(f"irrip.LVL={i}", f"level {i}") for i in range(1, 8)] \
        + [("irrip_default", "level 8 (I-RRIP)")]
    means(t, levels, "t2a_levels.tex", ref="rrip", ref_label="SRRIP")
    llc(t, [("base", "LRU"), ("irrip.LVL=1", "level 1"), ("irrip.LVL=3", "level 3"),
            ("irrip_default", "level 8")], "t2a_llc.tex")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for task, fn in [("task2a", task2a)]:
        if (DATA / task / "stats.csv").exists():
            fn()


if __name__ == "__main__":
    main()
