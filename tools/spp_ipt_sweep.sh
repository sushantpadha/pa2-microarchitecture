#!/usr/bin/env bash
# Sweep the SPP IP table size: IPT_SET_BITS {6,5,4} x IPT_WAYS {4,8}.
# Both are array sizes (#define), so getenv() can't sweep them. Instead this
# makes one copy of prefetcher/spp.l1d_pref per point (spp_s<bits>_w<ways>),
# writes exp/spp_ipt.toml, and runs it. The copies are deleted on exit.
#
#   tools/spp_ipt_sweep.sh            # final runs (25M + 25M, all traces)
#   tools/spp_ipt_sweep.sh --test     # extra args go to `exp.py run`
#   tools/exp.py show exp/spp_ipt.toml [--test]
set -euo pipefail
cd "$(dirname "$0")/.."

variants=()
trap 'rm -f "${variants[@]}"' EXIT

toml=exp/spp_ipt.toml
cat > "$toml" <<'EOF'
# SPP IP table size sweep, generated by tools/spp_ipt_sweep.sh.
metrics = ["ipc", "speedup", "l1d_load_mpki", "l1d_accuracy_issued", "l1d_accuracy_resolved", "l1d_coverage"]

[test]
warmup = 1_000_000
sim    = 5_000_000
EOF

for bits in 6 5 4; do
    for ways in 4 8; do
        name=spp_s${bits}_w${ways}
        f=prefetcher/$name.l1d_pref
        variants+=("$f")
        sed -e "s/^#define IPT_SET_BITS .*/#define IPT_SET_BITS  $bits/" \
            -e "s/^#define IPT_WAYS .*/#define IPT_WAYS      $ways/" \
            prefetcher/spp.l1d_pref > "$f"
        grep -q "^#define IPT_SET_BITS  $bits$" "$f" && grep -q "^#define IPT_WAYS      $ways$" "$f" \
            || { echo "sed did not patch $f" >&2; exit 1; }
        printf '\n[config.%s]\npf = "%s"\n' "$name" "$name" >> "$toml"
    done
done

tools/exp.py run "$toml" -j 23 "$@"
